let activeLocale = 'zh-CN';

export function setLocale(locale) {
  activeLocale = dictionaries[locale] ? locale : 'zh-CN';
  document.documentElement.lang = activeLocale;
  if (dictionaries[activeLocale].documentTitle) document.title = dictionaries[activeLocale].documentTitle;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = dictionaries[activeLocale][element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const value = dictionaries[activeLocale][element.dataset.i18nPlaceholder];
    if (value) element.setAttribute('placeholder', value);
  });
  return activeLocale;
}

export function translate(key, locale = activeLocale) {
  return dictionaries[locale]?.[key] || dictionaries['zh-CN'][key] || key;
}

export function getLocale() {
  return activeLocale;
}

export function getSupportedLocales() {
  return ['zh-CN', 'zh-TW', 'en', 'es', 'ko', 'fr'];
}
